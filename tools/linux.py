#!/usr/bin/env python3
"""Set up, build, launch and verify FA Remastered on Linux (Python standard library only)."""
import argparse
import ctypes.util
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
LOCAL = ROOT / '.fa-remaster'
FAF_REF = '4ef41e436a67f5936bae65c7de0677b639435a93'
DXC_URL = ('https://github.com/microsoft/DirectXShaderCompiler/releases/download/'
           'v1.8.2407/linux_dxc_2024_07_31.x86_64.tar.gz')
# This release loads on glibc 2.34 (CentOS 9); newer binaries require glibc 2.38.
DXC_SHA256 = 'b58725ac191df0686994fb9d54d27ee8dd3f180b023d562733112a499ea1195c'


def run(argv, **kwargs):
    print('+', ' '.join(map(str, argv)), flush=True)
    return subprocess.run(list(map(str, argv)), check=True, cwd=ROOT, **kwargs)


def require_game(game):
    if not (game / 'gamedata' / 'units.scd').is_file() or not (game / 'maps').is_dir():
        raise RuntimeError(f'{game}: expected the game folder containing gamedata/units.scd and maps/')


def fetch_dxc(build):
    if os.uname().machine != 'x86_64':
        raise RuntimeError('The pinned Linux DXC download is x86_64; provide your platform\'s libdxcompiler.so manually.')
    sdk = LOCAL / 'sdk'
    sdk.mkdir(parents=True, exist_ok=True)
    archive = sdk / 'linux_dxc_2024.tar.gz'
    if not archive.exists():
        partial = archive.with_suffix('.download')
        with urllib.request.urlopen(DXC_URL, timeout=120) as src, partial.open('wb') as dst:
            shutil.copyfileobj(src, dst)
        partial.replace(archive)
    if hashlib.sha256(archive.read_bytes()).hexdigest() != DXC_SHA256:
        raise RuntimeError(f'{archive}: checksum mismatch; remove it and retry')
    # Only extract the known runtime files and licences from the checksum verified archive.
    build.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive) as tar:
        members = {m.name.removeprefix('./'): m for m in tar.getmembers()}
        for name in ('lib/libdxcompiler.so', 'lib/libdxil.so', 'LICENSE-LLVM.txt', 'LICENSE-MS.txt'):
            member = members[name]
            if not member.isfile():
                raise RuntimeError(f'DXC archive entry is not a regular file: {name}')
            with tar.extractfile(member) as src, (build / Path(name).name).open('wb') as dst:
                shutil.copyfileobj(src, dst)
    print(f'DXC installed beside the programs in {build}')


def setup(a):
    LOCAL.mkdir(parents=True, exist_ok=True)
    game = LOCAL / 'game'
    source = Path(a.game).expanduser().resolve() if a.game else game
    require_game(source)
    if not game.exists():
        if a.copy_game:
            game.mkdir()
            run(['cp', '-a', '--reflink=auto', str(source) + '/.', game])
        else:
            game.symlink_to(source, target_is_directory=True)
    elif source != game.resolve():
        # Re-running setup must never merge a different installation into existing data.
        old = LOCAL / 'setup.json'
        previous = json.loads(old.read_text()) if old.exists() else {}
        if previous.get('source_game') != str(source):
            raise RuntimeError(f'{game} already exists; use --game {game} to reuse it')
    require_game(game)
    faf = LOCAL / 'faf'
    if a.faf:
        source_faf = Path(a.faf).expanduser().resolve()
        if not (source_faf / 'lua' / 'userInit.lua').is_file():
            raise RuntimeError('--faf must name a FAF source checkout, containing lua/userInit.lua')
        if not faf.exists():
            faf.symlink_to(source_faf, target_is_directory=True)
        elif faf.resolve() != source_faf:
            raise RuntimeError(f'{faf} already exists and points at another checkout')
    elif a.fetch_faf and not faf.exists():
        run(['git', 'init', faf])
        run(['git', '-C', faf, 'remote', 'add', 'origin', 'https://github.com/FAForever/fa.git'])
        run(['git', '-C', faf, 'fetch', '--depth', '1', 'origin', FAF_REF])
        run(['git', '-C', faf, 'checkout', '--detach', 'FETCH_HEAD'])
    paths = []
    if faf.exists():
        if not (faf / 'lua' / 'userInit.lua').is_file():
            raise RuntimeError(f'{faf}: incomplete FAF checkout')
        paths.append("    {dir = InitFileDir .. '/faf', mountpoint = '/'},")
    paths += ["    {dir = InitFileDir .. '/game/gamedata/*.scd', mountpoint = '/'},",
              "    {dir = InitFileDir .. '/game', mountpoint = '/'},"]
    (LOCAL / 'init_linux.lua').write_text(
        '-- Generated by tools/linux.py; mounts use native paths, first match wins.\n'
        'path = {\n' + '\n'.join(paths) + "\n}\nhook = {'/schook'}\n"
        "protocols = {'http', 'https', 'mailto'}\n", encoding='utf-8')
    revision = None
    if faf.exists():
        result = subprocess.run(['git', '-C', str(faf), 'rev-parse', 'HEAD'], capture_output=True, text=True)
        revision = result.stdout.strip() if result.returncode == 0 else None
    previous = json.loads((LOCAL / 'setup.json').read_text()) if (LOCAL / 'setup.json').exists() else {}
    (LOCAL / 'setup.json').write_text(json.dumps({
        'source_game': str(source) if a.game else previous.get('source_game', str(source)),
        'game': str(game), 'faf_revision': revision,
        'upstream_revision': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
    }, indent=2) + '\n')
    if a.fetch_dxc:
        fetch_dxc(a.build_dir)
    print(f'Ready: {LOCAL / "init_linux.lua"} (FAF overlay: {faf.exists()})')


def build(a):
    command = ['cmake', '-S', ROOT, '-B', a.build_dir, '-DCMAKE_BUILD_TYPE=RelWithDebInfo',
               '-DMOHO64_BUILD_UI=ON', '-DMOHO64_BUILD_VIEWER=' + ('OFF' if a.headless else 'ON'),
               '-DMOHO64_HEADLESS_UI=' + ('ON' if a.headless else 'OFF'),
               '-DMOHO64_FETCH_SDL3=' + ('ON' if a.fetch_sdl3 else 'OFF')]
    if shutil.which('ninja') and not (a.build_dir / 'CMakeCache.txt').exists():
        command += ['-G', 'Ninja']
    run(command)
    run(['cmake', '--build', a.build_dir, '--parallel', a.jobs])


def init_file():
    init = LOCAL / 'init_linux.lua'
    if not init.exists():
        raise RuntimeError('Run tools/linux.py setup --game <installation> first')
    return init


def launch(a):
    exe = a.build_dir / ('moho64' if a.sim else 'moho64view' if a.viewer else 'moho64ui')
    args = a.args[1:] if a.args[:1] == ['--'] else a.args
    command = [exe, '--init', init_file()]
    if a.viewer:
        command += ['--fa', LOCAL / 'game']
    elif not a.sim:
        command += ['--window']
    run(command + args)


def verify(a):
    sys.path.insert(0, str(ROOT / 'tests'))
    from framework import Runner, TestCase
    run(['ctest', '--test-dir', a.build_dir, '--output-on-failure'])
    mode = 'windowed' if a.window or a.game_window else 'headless'
    runner = Runner(ROOT, a.build_dir, init_file(), a.output, mode)
    cases = [
        TestCase('rules', host='sim', operation='rules', completion=False,
                 required=[r'rules state ok; registered:.*Unit=[1-9]']),
        TestCase('simulation', host='sim', session='tests/fixtures/skirmish.lua',
                 args=['--seed', '7', '--ticks', '300', '--view'], completion=False,
                 required=[r'ran 300 ticks', r'view: unit .*uel0001']),
        TestCase('menu', stage='frontend', window=False, frames=30, screenshot=True,
                 completion=False, required=[r'uimain.StartFrontEndUI ok', r'screenshot ']),
    ]
    cases += [TestCase(name, script=f'ui/tests/{name}.lua', window=False)
              for name in ('controls', 'lobby', 'keys', 'sound')]
    cases += [TestCase('game-orders', script='tests/ui/skirmish_smoke.lua', game_script=True,
                      session='tests/fixtures/skirmish.lua', window=False, frames=1500,
                      args=['--seed', '7'], screenshot=True)]
    if a.window or a.game_window:
        cases += [
            TestCase('input-contract', script='tests/ui/input_contract.lua', width=1280, height=720),
            TestCase('graphics-clear', host='viewer', operation='graphics_clear', width=320, height=240,
                     frames=3, screenshot=True, completion=False, required=[r'render: .+ on']),
            TestCase('graphics-pipelines', host='viewer', operation='graphics_pipelines', width=320, height=240,
                     frames=3, completion=False, required=[r'render: --gfx-check.*all right']),
        ]
    if a.game_window:
        cases += [TestCase('game-window', script='tests/ui/skirmish_smoke.lua', game_script=True,
                           setup='tests/ui/graphics_setup.lua', session='tests/fixtures/skirmish.lua',
                           world=True, frames=2400, width=640, height=360, args=['--seed', '7'],
                           capture_window=True, timeout=300, required=[r"the world's picture is open",
                           r"the window's picture is saved as .*_game.png"],
                           environment={'MOHO64UI_CAPTURE_FRAME': '80'})]
    print(f'Results: {runner.output}', flush=True)
    for case in cases:
        result = runner.run(case)
        print(f'{result.status.upper()} {result.name}: {result.log}', flush=True)
        if result.reason:
            print(result.reason, flush=True)
    if not all(result.status == 'passed' for result in runner.results):
        raise RuntimeError(f'Verification failed; see {runner.output / "results.json"}')
    print(f'All {len(cases)} runtime checks passed.')


def doctor(a):
    for command in ('cmake', 'c++', 'git', 'ninja', 'Xvfb'):
        print(f'{command}: {shutil.which(command) or "missing"}')
    print(f'display: {os.getenv("DISPLAY") or os.getenv("WAYLAND_DISPLAY") or "none (headless checks available)"}')
    for name in ('SDL3', 'vulkan', 'dxcompiler'):
        beside = a.build_dir / ('lib' + name + '.so')
        candidates = [beside, a.build_dir / '_deps/sdl3-build' / ('lib' + name + '.so')]
        candidates += [Path(p) / ('lib' + name + suffix) for p in ('/lib64', '/usr/lib64', '/usr/lib/x86_64-linux-gnu')
                       for suffix in ('.so', '.so.1', '.so.0')]
        library = next((str(p) for p in candidates if p.exists()), ctypes.util.find_library(name))
        # A managed Python can use a different loader than the native game. Report paths here;
        # verify --window exercises the libraries in the actual executable.
        print(f'{name}: {library or "missing"}')
    print(f'game init: {LOCAL / "init_linux.lua"} ({"ready" if (LOCAL / "init_linux.lua").exists() else "run setup"})')
    print('Hardware GPU devices:', ', '.join(str(p) for p in Path('/dev/dri').glob('render*')) or 'none')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--build-dir', type=Path, default=ROOT / 'build-native')
    commands = ap.add_subparsers(dest='command', required=True)
    p = commands.add_parser('setup', help='link/copy owned game data and generate native mounts')
    p.add_argument('--game', help='game installation folder (or reuse local game if omitted)')
    p.add_argument('--copy-game', action='store_true', help='copy instead of linking the game data')
    p.add_argument('--faf', help='use an existing FAF source checkout')
    p.add_argument('--fetch-faf', action='store_true', help='download FAF source scripts from GitHub')
    p.add_argument('--fetch-dxc', action='store_true', help='download checksum verified Linux x86_64 shader compiler')
    p.set_defaults(fn=setup)
    p = commands.add_parser('build', help='build the simulation, game interface and viewer with CMake')
    p.add_argument('--jobs', type=int, default=min(12, os.cpu_count() or 4))
    p.add_argument('--headless', action='store_true', help='simulation and interface without SDL/Vulkan')
    p.add_argument('--fetch-sdl3', action='store_true', help='build pinned SDL3 if the system has none')
    p.set_defaults(fn=build)
    p = commands.add_parser('run', help='launch the game; arguments after -- go to the engine')
    modes = p.add_mutually_exclusive_group()
    modes.add_argument('--sim', action='store_true')
    modes.add_argument('--viewer', action='store_true')
    p.add_argument('args', nargs=argparse.REMAINDER)
    p.set_defaults(fn=launch)
    p = commands.add_parser('verify', help='run shared engine/UI tests against your game data')
    p.add_argument('--output', type=Path, default=LOCAL / 'verification')
    p.add_argument('--window', action='store_true', help='also check SDL input and Vulkan; needs a display or Xvfb')
    p.add_argument('--game-window', action='store_true', help='also test rendered skirmish orders and capture the window; slower on Mesa software rendering')
    p.set_defaults(fn=verify)
    commands.add_parser('doctor', help='show build and runtime dependencies').set_defaults(fn=doctor)
    commands.add_parser('dxc', help='download checksum verified Linux x86_64 shader compiler').set_defaults(
        fn=lambda a: fetch_dxc(a.build_dir))
    a = ap.parse_args()
    a.build_dir = a.build_dir.expanduser().resolve()
    try:
        a.fn(a)
    except (OSError, RuntimeError, subprocess.CalledProcessError) as e:
        print(f'linux: {e}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
