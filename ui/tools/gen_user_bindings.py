"""Generate ui/user/user_binding_names.inc: the names of the original engine's Lua bindings of the
user (interface) state, and of the classes every state has (name + class only; the reference table
bindings.json is private and not shipped).
usage: gen_user_bindings.py <bindings.json> > ui/user/user_binding_names.inc"""
import json, sys

b = json.load(open(sys.argv[1]))
SETS = {'0xf59690': 'user', '0xf59680': 'core'}
rows = sorted({(SETS[x['head']], x['state'], x['name']) for x in b if x['head'] in SETS})
print('// Generated by ui/tools/gen_user_bindings.py: {set, C++ class ("" = global), name}')
for s, cls, name in rows:
    print(f'{{"{s}", "{"" if cls == "<global>" else cls}", "{name}"}},')
